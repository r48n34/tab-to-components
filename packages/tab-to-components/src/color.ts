/**
 * Normalize a CSS color option: trim it, accept hex / rgb / hsl / hwb / lab /
 * oklch / `color()` / named colors, and return `undefined` for anything else
 * so the theme's built-in crosshair colors stay in effect.
 */
export function normalizeCssColor(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  const color = value.trim();
  if (color === "" || color.length > MAX_CSS_COLOR_LENGTH) return undefined;
  if (HEX_COLOR.test(color) || FUNCTION_COLOR.test(color)) return color;
  if (NAMED_COLORS.has(color.toLowerCase())) return color;
  return undefined;
}
